//
// The initial stamp moved to /theme.js, which is render-blocking in <head>.
// This file is deferred, so doing it here meant a visitor whose stored choice
// differed from their OS painted the wrong theme first and flipped afterwards.
//
// Nothing here stamps data-theme for a visitor with no stored preference, and
// that is deliberate. style.css carries the dark tokens under
// `@media (prefers-color-scheme: dark) { :root:not([data-theme]) }`, so leaving
// the attribute off is what keeps the media query in control - which means an
// OS theme change with the page open now follows immediately, where the old
// code stamped `dark` once at load and froze it there until a reload.
const prefersDark = window.matchMedia('(prefers-color-scheme: dark)');

// The theme actually in effect, which is not always the attribute: with no
// attribute set, CSS is following the media query and the button has to agree.
function currentTheme() {
    const attr = document.documentElement.getAttribute('data-theme');
    if (attr === 'dark' || attr === 'light') return attr;
    return prefersDark.matches ? 'dark' : 'light';
}

function initThemeToggle() {
    // Find the toggle button (inserted via HTML)
    const toggle = document.querySelector('.theme-toggle');
    if (!toggle) return;

    updateToggleIcon(toggle);

    toggle.addEventListener('click', function () {
        const next = currentTheme() === 'dark' ? 'light' : 'dark';
        document.documentElement.setAttribute('data-theme', next);
        try {
            localStorage.setItem('theme', next);
        } catch (e) {
            /* Private mode or blocked storage: the choice holds for this page
               and simply does not persist. Not worth failing the click over. */
        }
        updateToggleIcon(this);
    });

    // While no explicit choice is stored the page tracks the OS, so the icon
    // has to track it too.
    const onSystemChange = function () {
        if (!document.documentElement.hasAttribute('data-theme')) {
            updateToggleIcon(toggle);
        }
    };
    if (prefersDark.addEventListener) {
        prefersDark.addEventListener('change', onSystemChange);
    } else if (prefersDark.addListener) {
        prefersDark.addListener(onSystemChange);
    }
}

function updateToggleIcon(btn) {
    const isDark = currentTheme() === 'dark';
    btn.textContent = isDark ? '☀️' : '🌙';
    btn.setAttribute('aria-label', isDark ? 'Switch to light mode' : 'Switch to dark mode');
}

// Search suggestions / autocomplete
function initSearchSuggestions() {
    const input = domCache.searchInput;
    if (!input) return;

    // Wrap input in search-wrapper for positioning
    const wrapper = document.createElement('div');
    wrapper.className = 'search-wrapper';
    input.parentNode.insertBefore(wrapper, input);
    wrapper.appendChild(input);

    // Create suggestions dropdown
    const dropdown = document.createElement('div');
    dropdown.className = 'search-suggestions';
    dropdown.setAttribute('role', 'listbox');
    dropdown.id = 'searchSuggestions';
    wrapper.appendChild(dropdown);

    input.setAttribute('role', 'combobox');
    input.setAttribute('aria-autocomplete', 'list');
    input.setAttribute('aria-controls', 'searchSuggestions');
    input.setAttribute('aria-expanded', 'false');

    // Build suggestion index from cards
    const suggestions = buildSuggestionIndex();
    let highlightIndex = -1;

    const debouncedSuggest = debounce(function() {
        const query = input.value.trim().toLowerCase();
        if (query.length < 2) {
            closeSuggestions();
            return;
        }

        const matches = suggestions.filter(s =>
            s.text.toLowerCase().includes(query)
        ).slice(0, 8);

        if (matches.length === 0) {
            closeSuggestions();
            return;
        }

        dropdown.innerHTML = '';
        matches.forEach((match, i) => {
            const div = document.createElement('div');
            div.className = 'search-suggestion';
            div.setAttribute('role', 'option');
            div.dataset.value = match.text;
            div.innerHTML = `<span>${sanitize(match.text)}</span><span class="suggestion-type">${sanitize(match.type)}</span>`;
            div.addEventListener('mousedown', function(e) {
                e.preventDefault();
                input.value = match.text;
                closeSuggestions();
                filterResources(match.text.toLowerCase());
            });
            dropdown.appendChild(div);
        });

        highlightIndex = -1;
        dropdown.classList.add('visible');
        input.setAttribute('aria-expanded', 'true');
    }, 100);

    input.addEventListener('input', debouncedSuggest);

    input.addEventListener('keydown', function(e) {
        const items = dropdown.querySelectorAll('.search-suggestion');
        if (!dropdown.classList.contains('visible') || items.length === 0) return;

        if (e.key === 'ArrowDown') {
            e.preventDefault();
            highlightIndex = Math.min(highlightIndex + 1, items.length - 1);
            updateHighlight(items, highlightIndex);
        } else if (e.key === 'ArrowUp') {
            e.preventDefault();
            highlightIndex = Math.max(highlightIndex - 1, 0);
            updateHighlight(items, highlightIndex);
        } else if (e.key === 'Enter' && highlightIndex >= 0) {
            e.preventDefault();
            input.value = items[highlightIndex].dataset.value;
            closeSuggestions();
            filterResources(input.value.toLowerCase());
        } else if (e.key === 'Escape') {
            closeSuggestions();
        }
    });

    input.addEventListener('blur', function() {
        setTimeout(closeSuggestions, 150);
    });

    function closeSuggestions() {
        dropdown.classList.remove('visible');
        dropdown.innerHTML = '';
        highlightIndex = -1;
        input.setAttribute('aria-expanded', 'false');
    }

    function updateHighlight(items, index) {
        items.forEach(item => item.classList.remove('highlighted'));
        if (index >= 0 && index < items.length) {
            items[index].classList.add('highlighted');
            items[index].scrollIntoView({ block: 'nearest' });
        }
    }
}

function buildSuggestionIndex() {
    const seen = new Set();
    const suggestions = [];
    const cards = document.querySelectorAll('.resource-card');

    cards.forEach(card => {
        // Add card titles
        const title = card.querySelector('h3')?.textContent.trim();
        if (title && !seen.has(title.toLowerCase())) {
            seen.add(title.toLowerCase());
            suggestions.push({ text: title, type: 'Resource' });
        }

        // Add tags
        card.querySelectorAll('.tag').forEach(tag => {
            const t = tag.textContent.trim();
            if (t && !seen.has(t.toLowerCase())) {
                seen.add(t.toLowerCase());
                suggestions.push({ text: t, type: 'Tag' });
            }
        });
    });

    return suggestions;
}

// Social sharing buttons (news page)
function initShareButtons() {
    if (!document.body.classList.contains('news-page')) return;

    document.querySelectorAll('.resource-card').forEach(card => {
        const cardLink = card.closest('.card-link');
        if (!cardLink) return;

        const url = cardLink.href;
        const title = card.querySelector('h3')?.textContent.trim() || '';
        const encodedUrl = encodeURIComponent(url);
        const encodedTitle = encodeURIComponent(title);

        const container = document.createElement('div');
        container.className = 'share-buttons';

        container.innerHTML =
            `<a href="https://www.linkedin.com/sharing/share-offsite/?url=${encodedUrl}" class="share-btn share-btn--linkedin" target="_blank" rel="noopener noreferrer" aria-label="Share on LinkedIn" title="Share on LinkedIn">in</a>` +
            `<a href="https://twitter.com/intent/tweet?url=${encodedUrl}&text=${encodedTitle}" class="share-btn share-btn--twitter" target="_blank" rel="noopener noreferrer" aria-label="Share on X" title="Share on X">X</a>` +
            `<a href="https://bsky.app/intent/compose?text=${encodedTitle}%20${encodedUrl}" class="share-btn share-btn--bluesky" target="_blank" rel="noopener noreferrer" aria-label="Share on Bluesky" title="Share on Bluesky">🦋</a>` +
            `<a href="https://www.reddit.com/submit?url=${encodedUrl}&title=${encodedTitle}" class="share-btn share-btn--reddit" target="_blank" rel="noopener noreferrer" aria-label="Share on Reddit" title="Share on Reddit">r/</a>`;

        // Prevent share button clicks from navigating the parent card-link
        container.addEventListener('click', function(e) {
            e.stopPropagation();
        });

        card.appendChild(container);
    });
}

// Resource card tooltips
function initTooltips() {
    // Skip on touch devices - no hover available
    if (window.matchMedia('(hover: none) and (pointer: coarse)').matches) return;

    var tooltip = document.createElement('div');
    tooltip.className = 'resource-tooltip';
    tooltip.setAttribute('role', 'tooltip');
    tooltip.setAttribute('aria-label', 'Resource description');
    tooltip.setAttribute('aria-hidden', 'true');
    tooltip.id = 'resourceTooltip';
    document.body.appendChild(tooltip);

    var showTimeout = null;
    var currentCard = null;

    var container = document.getElementById('main-content');
    if (!container) return;

    container.addEventListener('mouseover', function (e) {
        var card = e.target.closest('.resource-card[data-tooltip]');
        if (!card || card === currentCard) return;

        currentCard = card;
        clearTimeout(showTimeout);

        showTimeout = setTimeout(function () {
            tooltip.textContent = card.dataset.tooltip;
            card.setAttribute('aria-describedby', 'resourceTooltip');
            tooltip.setAttribute('aria-hidden', 'false');
            tooltip.classList.add('visible');
            requestAnimationFrame(function () {
                cachedTw = tooltip.offsetWidth || 360;
                cachedTh = tooltip.offsetHeight || 60;
            });
        }, 300);
    });

    var cachedTw = 360;
    var cachedTh = 60;
    container.addEventListener('mousemove', function (e) {
        if (!tooltip.classList.contains('visible') && !showTimeout) return;

        var pad = 12;
        var edge = 8;
        var tw = cachedTw;
        var th = cachedTh;

        var x = e.clientX + pad;
        var y = e.clientY + pad;

        if (x + tw > window.innerWidth - edge) x = e.clientX - tw - pad;
        if (y + th > window.innerHeight - edge) y = e.clientY - th - pad;
        x = Math.max(edge, x);
        y = Math.max(edge, y);

        tooltip.style.left = x + 'px';
        tooltip.style.top = y + 'px';
    });

    container.addEventListener('mouseout', function (e) {
        var card = e.target.closest('.resource-card[data-tooltip]');
        if (!card) return;

        var related = e.relatedTarget;
        if (related && card.contains(related)) return;

        clearTimeout(showTimeout);
        showTimeout = null;
        currentCard = null;
        tooltip.classList.remove('visible');
        tooltip.setAttribute('aria-hidden', 'true');
        card.removeAttribute('aria-describedby');
    });
}

// Add a site-wide "Search" link to the top-level header nav. Runs on every
// page that loads main.js - saves us from editing the hardcoded <nav> in
// ~30 HTML files. The link points at /search.html, where the Pagefind UI
// renders. Idempotent: if a search link already exists in the markup (e.g.
// search.html itself adds one statically in the future), the function does
// nothing.
function injectSearchLink() {
    const navUl = document.querySelector('header nav > ul');
    if (!navUl) return;
    if (navUl.querySelector('.nav-search-item')) return;

    const li = document.createElement('li');
    li.className = 'nav-search-item';

    const a = document.createElement('a');
    a.href = '/search.html';
    a.className = 'nav-search-link';
    a.setAttribute('aria-label', 'Search the site');
    // Magnifying glass + visible "Search" label so the affordance reads
    // clearly on both desktop and the mobile hamburger menu. The wrapping
    // span lets CSS shorten / hide the text on tight viewports later.
    a.innerHTML = '<span aria-hidden="true">🔍</span> <span class="nav-search-text">Search</span>';

    // If the current page IS /search.html, mark the link as the current page
    // so it gets the same styling as other active nav items.
    if (location.pathname.replace(/^\/+/, '').toLowerCase() === 'search.html') {
        a.setAttribute('aria-current', 'page');
    }

    li.appendChild(a);

    // Insert before the trailing support/CTA pair (Support, Join Friday Zoom)
    // so it lives in the primary nav region, not after the call-to-action.
    // Fall back to appending if neither is on this page.
    const tail = navUl.querySelector('.nav-coffee-item, .nav-cta-item');
    if (tail) navUl.insertBefore(li, tail);
    else navUl.appendChild(li);
}

function initDropdownNav() {
    const items = document.querySelectorAll('.has-dropdown');
    if (!items.length) return;

    const isMobile = () => window.matchMedia('(max-width: 768px)').matches;

    const closeAll = (except) => {
        items.forEach(item => {
            if (item === except) return;
            item.classList.remove('open');
            const toggle = item.querySelector('.dropdown-toggle');
            if (toggle) toggle.setAttribute('aria-expanded', 'false');
        });
    };

    items.forEach(item => {
        const toggle = item.querySelector('.dropdown-toggle');
        if (!toggle) return;

        toggle.addEventListener('click', (e) => {
            e.preventDefault();
            e.stopPropagation();
            const willOpen = !item.classList.contains('open');
            closeAll(item);
            item.classList.toggle('open', willOpen);
            toggle.setAttribute('aria-expanded', String(willOpen));
        });

        toggle.addEventListener('keydown', (e) => {
            if (e.key === 'Escape') {
                item.classList.remove('open');
                toggle.setAttribute('aria-expanded', 'false');
                toggle.focus();
            }
        });

        const menu = item.querySelector('.dropdown-menu');
        if (menu) {
            menu.addEventListener('keydown', (e) => {
                if (e.key === 'Escape') {
                    item.classList.remove('open');
                    toggle.setAttribute('aria-expanded', 'false');
                    toggle.focus();
                }
            });
        }
    });

    document.addEventListener('click', (e) => {
        if (!e.target.closest('.has-dropdown')) closeAll(null);
    });

    document.addEventListener('keydown', (e) => {
        if (e.key === 'Escape') closeAll(null);
    });
}
// Localize the weekly session time. The session is Friday 07:00-08:00
// America/Los_Angeles; csoh.ics is the source of truth for both ends.
// Three consumers:
//   [data-session-localtime] - inline "(that's X your time)" after an
//     advertised "7am PT", so members outside Pacific don't do the math.
//   [data-next-session]      - the homepage next-session banner, which needs
//     the concrete upcoming date, not just the weekly cadence.
//   [data-session-countdown] - the homepage countdown, which ticks once a
//     second and shows "live now" during the hour itself rather than a
//     six-day countdown to the following week. See resolve().
// Purely additive: without Intl - or without JS at all - the markup keeps its
// server-rendered text, and the countdown stays hidden because only the code
// below adds the --on class that reveals it.
(function () {
    var TZ = 'America/Los_Angeles';
    var DURATION_MS = 60 * 60 * 1000;   // csoh.ics: DTSTART 07:00, DTEND 08:00
    var els = document.querySelectorAll('[data-session-localtime]');
    var nextEls = document.querySelectorAll('[data-next-session]');
    var countdown = document.querySelector('[data-session-countdown]');
    if (!els.length && !nextEls.length && !countdown) return;
    if (typeof Intl === 'undefined' || !Intl.DateTimeFormat) return;

    // Offset (ms) of TZ at a given instant: local wall time minus UTC.
    function tzOffset(instant) {
        var parts = new Intl.DateTimeFormat('en-US', {
            timeZone: TZ, hour12: false,
            year: 'numeric', month: '2-digit', day: '2-digit',
            hour: '2-digit', minute: '2-digit', second: '2-digit'
        }).formatToParts(instant);
        var m = {};
        for (var i = 0; i < parts.length; i++) m[parts[i].type] = parts[i].value;
        var hour = m.hour === '24' ? '00' : m.hour;
        var asUTC = Date.UTC(+m.year, +m.month - 1, +m.day, +hour, +m.minute, +m.second);
        return asUTC - instant.getTime();
    }

    // Instant of 07:00 PT on the Pacific calendar day containing `probe`, or
    // null if that day is not a Friday. (Friday 7am is never near a DST
    // switch, so the offset at 07:00 UTC that day equals the real one.)
    function sessionOn(probe) {
        if (new Intl.DateTimeFormat('en-US', { timeZone: TZ, weekday: 'short' }).format(probe) !== 'Fri') return null;
        var ymd = new Intl.DateTimeFormat('en-CA', {
            timeZone: TZ, year: 'numeric', month: '2-digit', day: '2-digit'
        }).format(probe).split('-');
        var naiveUTC = Date.UTC(+ymd[0], +ymd[1] - 1, +ymd[2], 7, 0, 0);
        return new Date(naiveUTC - tzOffset(new Date(naiveUTC)));
    }

    // The session worth talking about: the one under way, else the next to
    // start. The in-progress case is the whole reason this isn't just "next
    // start" - at 07:30 on a Friday the next start is six days out, and a
    // banner counting down to next week while people are in the room is the
    // one moment this component must not get wrong.
    function resolve(nowMs) {
        for (var d = 0; d < 8; d++) {
            var start = sessionOn(new Date(nowMs + d * 86400000));
            if (!start) continue;
            var t = start.getTime();
            if (nowMs < t) return { live: false, start: start };
            if (nowMs < t + DURATION_MS) return { live: true, start: start };
        }
        return null;
    }

    var state = resolve(Date.now());
    if (!state) return;

    var viewerTZ = '';
    try { viewerTZ = Intl.DateTimeFormat().resolvedOptions().timeZone || ''; } catch (e) {}
    var isPacific = viewerTZ === TZ;

    // Banner: name the actual upcoming date, then the viewer's local clock
    // time. Re-rendered on a state flip so a page left open across 07:00
    // stops advertising a session that has already started.
    function renderBanner() {
        if (!nextEls.length) return;
        var when;
        if (state.live) {
            when = 'Happening now - 7:00 to 8:00 AM PT';
        } else {
            when = new Intl.DateTimeFormat('en-US', {
                timeZone: TZ, weekday: 'long', month: 'long', day: 'numeric'
            }).format(state.start) + ' at 7:00 AM PT';
            if (!isPacific) {
                when += ' · ' + new Intl.DateTimeFormat(undefined, {
                    hour: 'numeric', minute: '2-digit', timeZoneName: 'short'
                }).format(state.start) + ' your time';
            }
        }
        for (var k = 0; k < nextEls.length; k++) nextEls[k].textContent = when;
    }
    renderBanner();

    if (countdown) (function () {
        var UNITS = ['days', 'hours', 'minutes', 'seconds'];
        var wrap = {}, num = {}, label = {};
        for (var u = 0; u < UNITS.length; u++) {
            var n = UNITS[u];
            wrap[n] = countdown.querySelector('[data-unit="' + n + '"]');
            num[n] = wrap[n] && wrap[n].querySelector('.next-session__unit-num');
            label[n] = wrap[n] && wrap[n].querySelector('.next-session__unit-label');
            if (!num[n] || !label[n]) return;   // markup changed - leave it hidden
        }

        function set(el, text) { if (el.textContent !== text) el.textContent = text; }

        function paint(nowMs) {
            countdown.classList.toggle('next-session__countdown--live', state.live);
            if (state.live) return;
            var secs = Math.floor(Math.max(0, state.start.getTime() - nowMs) / 1000);
            var value = {
                days: Math.floor(secs / 86400),
                hours: Math.floor(secs % 86400 / 3600),
                minutes: Math.floor(secs % 3600 / 60),
                seconds: secs % 60
            };
            // Drop the days tile rather than show "0 days" on the last day:
            // a zeroed leading unit reads as broken, not as "soon".
            wrap.days.hidden = value.days === 0;
            for (var i = 0; i < UNITS.length; i++) {
                var n = UNITS[i];
                set(num[n], n === 'days' || value[n] > 9 ? String(value[n]) : '0' + value[n]);
                set(label[n], value[n] === 1 ? n.slice(0, -1) : n);
            }
        }

        // Recompute from the clock every tick rather than decrementing a
        // counter: background tabs throttle timers, and a machine that sleeps
        // for an hour must wake up showing the truth, not an hour of drift.
        function tick() {
            var nowMs = Date.now();
            if (nowMs >= state.start.getTime() + (state.live ? DURATION_MS : 0)) {
                var next = resolve(nowMs);
                if (next) {
                    state = next;
                    renderBanner();
                }
            }
            paint(nowMs);
        }

        paint(Date.now());
        countdown.classList.add('next-session__countdown--on');
        setInterval(tick, 1000);
    })();

    if (!els.length || isPacific) return; // already Pacific - nothing to add
    var local = new Intl.DateTimeFormat(undefined, {
        weekday: 'long', hour: 'numeric', minute: '2-digit', timeZoneName: 'short'
    }).format(state.start);
    for (var j = 0; j < els.length; j++) {
        els[j].textContent = ' (that’s ' + local + ' your time)';
    }
})();
