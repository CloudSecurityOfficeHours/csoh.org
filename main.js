// news.html's article cards are rewritten from the RSS feeds every week by
// update-news.yml, so they cannot carry a hand-placed data-icon - anything
// added here would be dropped at the next refresh. The generator does stamp a
// stable data-category on each card, which is a far better signal than the
// padlock the keyword classifier below falls back to. These three values are
// news.html's alone; no other page uses them.
const CARD_CATEGORY_ICONS = {
    report: '\u{1F4F0}',
    vulnerability: '\u26A0\uFE0F',
    breach: '\u{1F6A8}'
};

function addIconsToCards() {
    // Opt-out for pages whose cards are deliberately text-only. The classifier
    // below keys off tags and title keywords and falls back to a generic
    // padlock when it cannot place a card, which is fine for the third-party
    // directory it was written for. On an index of our own topic pages nothing
    // matches, so every card renders the same glyph: 40 identical padlocks that
    // encode nothing and cost a row of height each. topics.html sets
    // data-no-card-icons on <main> for that reason.
    if (document.querySelector('[data-no-card-icons]')) return;

    const cards = document.querySelectorAll('.resource-card');
    
    cards.forEach(card => {
        // Skip if icon already exists or card has a banner/preview image
        if (card.querySelector('.resource-card-icon')) return;
        if (card.querySelector('.resource-preview')) return;
        
        const tags = Array.from(card.querySelectorAll('.tag')).map(tag => tag.textContent.toLowerCase());
        const title = card.querySelector('h3').textContent.toLowerCase();
        
        let icon = '🔐'; // default security icon
        let iconClass = '';

        // Helper: exact tag match (case-insensitive). Avoids substring false-positives
        // like "Daily" matching "ai" or "Chain" matching "ai".
        const tagEquals = (needle) => tags.some(tag => tag === needle);

        // Determine icon based on tags and content. Order matters - earlier matches win.
        //
        // An authored page names its own glyph and wins outright. The classifier
        // below was written for the third-party resource directory, where every
        // card carries a tag like "Tool" or "CTF"; on a page of our own prose
        // cards nothing matches and all of them render the same padlock. The fix
        // is not more title keywords - those guess, and drift the moment a
        // heading is reworded - it is letting the page say what it means.
        if (card.dataset.icon) {
            icon = card.dataset.icon;
        } else if (tagEquals('newsletter')) {
            icon = '📬';
            iconClass = 'newsletter';
        } else if (tagEquals('blog')) {
            icon = '✍️';
            iconClass = 'blog';
        } else if (tagEquals('podcast')) {
            icon = '🎙️';
            iconClass = 'podcast';
        } else if (tags.some(tag => tag.includes('ctf')) || title.includes('ctf') || title.includes('goat') || title.includes('vulnerable')) {
            icon = '🎯';
            iconClass = 'ctf';
        } else if (tags.some(tag => tag.includes('tool')) || tags.some(tag => tag.includes('cspm')) || tags.some(tag => tag.includes('cnapp'))) {
            icon = '🛠️';
            iconClass = 'tool';
        } else if (tags.some(tag => tag.includes('certification')) || title.includes('cert')) {
            icon = '🎓';
            iconClass = 'certification';
        } else if (tags.some(tag => tag.includes('lab') || tag.includes('hands-on') || tag.includes('training'))) {
            icon = '🧪';
            iconClass = 'lab';
        } else if (tags.some(tag => tag.includes('kubernetes') || tag.includes('k8s')) || title.includes('kubernetes')) {
            icon = '☸️';
            iconClass = 'kubernetes';
        } else if (tagEquals('ai') || tagEquals('ml') || tagEquals('ai-security') || tagEquals('ai security') || /\bai\b/.test(title)) {
            icon = '🤖';
            iconClass = 'ai';
        } else if (title.includes('aws')) {
            icon = '☁️';
            iconClass = 'tool';
        } else if (title.includes('azure')) {
            icon = '☁️';
            iconClass = 'tool';
        } else if (title.includes('gcp') || title.includes('google cloud')) {
            icon = '☁️';
            iconClass = 'tool';
        } else if (CARD_CATEGORY_ICONS[card.dataset.category]) {
            icon = CARD_CATEGORY_ICONS[card.dataset.category];
        }
        
        // Create icon element
        const iconDiv = document.createElement('div');
        iconDiv.className = `resource-card-icon ${iconClass}`.trim();
        iconDiv.textContent = icon;
        
        // Insert icon at the beginning of the card
        card.insertBefore(iconDiv, card.firstChild);
    });
}

// Insert a small preview screenshot for each resource card.
// Uses WordPress mShots service to generate a lightweight thumbnail.
function addPreviewImagesToCards() {
    const cards = document.querySelectorAll('.resource-card');

    cards.forEach(card => {
        // Skip if card marked as no-preview (e.g., index page category cards)
        if (card.hasAttribute('data-no-preview')) return;

        // avoid duplicating previews
        if (card.querySelector('.resource-preview')) return;

        const link = card.querySelector('h3 a');
        if (!link) return;

        const url = link.href;
        if (!url) return;

        // Skip cards with no local preview available - no third-party fallback.
        // (Avoids inserting an empty <img> that renders as a broken-image placeholder.)
        if (!previewMap[url]) return;

        const img = document.createElement('img');
        img.className = 'resource-preview';
        img.alt = `Preview of ${link.textContent.trim()}`;
        img.loading = 'lazy';
        img.referrerPolicy = 'no-referrer';
        img.decoding = 'async';
        // Set explicit dimensions to prevent layout shift
        img.width = 600;
        img.height = 160;

        img.src = previewMap[url];
        img.onerror = function() { img.remove(); };

        // Place the preview after any icon but before the title
        const icon = card.querySelector('.resource-card-icon');
        if (icon && icon.nextSibling) {
            card.insertBefore(img, icon.nextSibling);
        } else if (icon) {
            card.appendChild(img);
        } else {
            card.insertBefore(img, card.firstChild);
        }
    });
}

// Helper: get the element to show/hide for a given card.
// On news.html cards are wrapped in <a class="card-link">, on resources.html they are standalone.
function getToggleTarget(card) {
    const parent = card.parentElement;
    return (parent && parent.classList.contains('card-link')) ? parent : card;
}

function filterResources(searchTerm) {
    // Use cached cards or query if not available
    const cards = domCache.cards.length > 0 ? domCache.cards : document.querySelectorAll('.resource-card');
    
    // Use requestAnimationFrame for smoother rendering
    requestAnimationFrame(() => {
        cards.forEach(card => {
            const title = card.querySelector('h3')?.textContent.toLowerCase() || '';
            const paragraphs = Array.from(card.querySelectorAll('p')).map(p => p.textContent).join(' ').toLowerCase();
            const tags = Array.from(card.querySelectorAll('.tag')).map(tag => tag.textContent.toLowerCase()).join(' ');

            const matches = title.includes(searchTerm) ||
                           paragraphs.includes(searchTerm) ||
                           tags.includes(searchTerm);

            getToggleTarget(card).style.display = matches ? '' : 'none';
        });

        updateVisibleCount();
    });
}

function updateVisibleCount() {
    // Use cached cards or query if not available
    const cards = domCache.cards.length > 0 ? domCache.cards : document.querySelectorAll('.resource-card');
    let visibleCount = 0;

    cards.forEach(card => {
        if (getToggleTarget(card).style.display !== 'none') {
            visibleCount++;
        }
    });

    const countElement = document.getElementById('visibleCount');
    if (countElement) {
        countElement.textContent = visibleCount;
    }

    // Show/hide "no results" message
    const noResults = document.getElementById('noResults');
    if (noResults) {
        // '' would fall back to .no-results { display: none } in CSS, so be explicit.
        noResults.style.display = visibleCount === 0 ? 'block' : 'none';
    }

    // Announce to screen readers
    const announce = document.getElementById('searchAnnounce');
    if (announce) {
        announce.textContent = visibleCount === 0
            ? 'No resources match your search.'
            : 'Showing ' + visibleCount + ' resource' + (visibleCount !== 1 ? 's' : '') + '.';
    }
}

// Sticky-header offset for anchor jumps.
// The header's height varies by viewport (the nav collapses to a hamburger on
// mobile and wraps to multiple rows in a narrow band above that), so a single
// fixed CSS value can't keep linked headings clear of it everywhere. Measure
// the real height and publish it as --header-height; html { scroll-padding-top }
// consumes it. CSS holds sane fallbacks if this never runs.
function initHeaderHeightVar() {
    const header = document.querySelector('header');
    if (!header) return;
    const root = document.documentElement;
    const measure = function () {
        // Only offset when the header actually overlaps content. On mobile the
        // header is position:static (it scrolls away), so no offset is needed
        // and any would just leave dead space at the top after a jump.
        const pos = getComputedStyle(header).position;
        const sticks = pos === 'sticky' || pos === 'fixed';
        // A little breathing room so the heading isn't flush against the bar.
        const h = sticks ? Math.round(header.getBoundingClientRect().height) + 12 : 0;
        root.style.setProperty('--header-height', h + 'px');
    };
    // Measure now: the nav DOM is settled by this point and the site uses the
    // system font stack, so there's no async web-font reflow to wait on.
    measure();
    window.addEventListener('load', measure);            // belt-and-suspenders re-measure
    // Throttle resize with rAF (the page is visible while the user drags).
    let raf = 0;
    window.addEventListener('resize', function () {
        if (!raf) raf = requestAnimationFrame(function () { raf = 0; measure(); });
    }, { passive: true });
}

